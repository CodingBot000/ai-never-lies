import { createHash } from 'node:crypto'
import { readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = new URL('../dist/', import.meta.url)
const rootPath = fileURLToPath(root)

async function filesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = join(directory, entry.name)
      if (entry.isDirectory()) return filesUnder(fullPath)
      return entry.name === 'sw.js' ? [] : [fullPath]
    }),
  )
  return nested.flat()
}

const files = (await filesUnder(rootPath)).sort()
const records = await Promise.all(
  files.map(async (file) => {
    const metadata = await stat(file)
    const sha256 = createHash('sha256').update(await readFile(file)).digest('hex')
    return {
      path: relative(rootPath, file).split(sep).join('/'),
      size: metadata.size,
      sha256,
    }
  }),
)

const version = createHash('sha256').update(JSON.stringify(records)).digest('hex').slice(0, 16)
const resources = ['./', ...records.filter((item) => item.path !== 'index.html').map((item) => `./${item.path}`)]
const worker = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE_NAME = 'anl-ep01-${version}'
const PRECACHE_RESOURCES = ${JSON.stringify(resources, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME)
    const urls = PRECACHE_RESOURCES.map((path) => new URL(path, self.registration.scope).href)
    await cache.addAll(urls)
    // 열린 탭은 기존 해시 자산과 기존 캐시를 계속 사용한다. 새 워커는
    // 표준 waiting 상태를 거쳐 다음 세션에서 활성화되어 업데이트 중 빈 화면을 막는다.
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys()
    await Promise.all(names.filter((name) => name.startsWith('anl-ep01-') && name !== CACHE_NAME).map((name) => caches.delete(name)))
    await self.clients.claim()
  })())
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  event.respondWith((async () => {
    // Vite preview는 폰트에 Vary: Origin을 붙인다. 선캐시 요청과 런타임
    // 폰트 요청의 Origin 헤더 차이 때문에 같은 URL을 놓치지 않게 한다.
    const cached = await caches.match(request, { ignoreVary: true })
    if (cached) return cached
    try {
      const response = await fetch(request)
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME)
        await cache.put(request, response.clone())
      }
      return response
    } catch (error) {
      if (request.mode === 'navigate') {
        const fallback = await caches.match(new URL('./', self.registration.scope).href)
        if (fallback) return fallback
      }
      throw error
    }
  })())
})
`

await writeFile(new URL('../dist/sw.js', import.meta.url), worker, 'utf8')
const totalBytes = records.reduce((sum, item) => sum + item.size, 0)
console.log(`service worker: ${records.length} files, ${(totalBytes / 1024 / 1024).toFixed(2)}MB, cache ${version}`)
